/**
 * The verse for a day: fixed for the whole day, different the next.
 *
 * Hashed off the date rather than taken in order, so it neither reshuffles on
 * every render nor marches through the list in a rhythm the reader can feel.
 */
export function verseFor(day: DayKey): Verse {
  let hash = 7;
  for (const char of day) hash = (hash * 131 + char.charCodeAt(0)) % 1_000_003;
  return VERSES[hash % VERSES.length];
}
